"""Generate a frozen NuGet ID profile from hash-pinned official Unicode data.

Offline only. Download the named versions from unicode.org separately. This
generator never reads an SDK or changes fixture expectations to match Go.
"""
import argparse
import hashlib
from pathlib import Path

WORD_SHA256 = 'ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f'
CASE_SHA256 = '2fc713e6a31a87c4850a37fe2caffa4218180fadb5de86b43a143ddb4581fb86'
WORD_CATEGORIES = {'Lu', 'Ll', 'Lt', 'Lm', 'Lo', 'Mn', 'Nd', 'Pc'}


def records(path, expected):
    with path.open('rb') as source:
        raw = source.read((4 << 20) + 1)
    if len(raw) > 4 << 20 or hashlib.sha256(raw).hexdigest() != expected:
        raise SystemExit('Unicode input hash/size does not match the pinned profile')
    pending = None
    for line in raw.decode('utf-8').splitlines():
        row = line.split(';')
        if len(row) != 15:
            raise SystemExit('Malformed pinned Unicode record')
        code = int(row[0], 16)
        if row[1].endswith(', First>'):
            if pending is not None:
                raise SystemExit('Nested Unicode range')
            pending = (code, row[2])
        elif row[1].endswith(', Last>'):
            if pending is None or pending[1] != row[2]:
                raise SystemExit('Unmatched Unicode range')
            start, category = pending
            for scalar in range(start, min(code, 0xffff) + 1):
                yield scalar, category, ''
            pending = None
        else:
            if code <= 0xffff:
                yield code, row[2], row[13]
    if pending is not None:
        raise SystemExit('Unclosed Unicode range')


def generate(word_path, case_path):
    words = sorted(code for code, category, _ in records(word_path, WORD_SHA256) if category in WORD_CATEGORIES)
    ranges = []
    for code in words:
        if ranges and code == ranges[-1][1] + 1:
            ranges[-1][1] = code
        else:
            ranges.append([code, code])
    pairs = [(code, int(lower, 16)) for code, _, lower in records(case_path, CASE_SHA256) if lower]
    if any(lower > 0xffff for _, lower in pairs):
        raise SystemExit('Unexpected supplementary lowercase mapping')
    lines = [
        '// SPDX-License-Identifier: BUSL-1.1 AND Unicode-3.0',
        '// Code generated by scripts/generate_nuget_id_profile.py; DO NOT EDIT.',
        '// Unicode data copyright 1991-2026 Unicode, Inc. See third_party/licenses/Unicode-3.0.txt.',
        '// Word data: https://www.unicode.org/Public/16.0.0/ucd/UnicodeData.txt',
        '// SHA256: ' + WORD_SHA256,
        '// Case data: https://www.unicode.org/Public/15.1.0/ucd/UnicodeData.txt',
        '// SHA256: ' + CASE_SHA256,
        'package nuget', '',
        'const IDKeyProfile = "legacy-word-u16.0.0-invariant-lower-u15.1.0-v1"', '',
        'type idUnicodeRange struct{ lo, hi uint16 }',
        'type idUnicodeLower struct{ from, to uint16 }', '',
        'var idWordRanges = [...]idUnicodeRange{']
    lines.extend(f'\t{{0x{lo:04x}, 0x{hi:04x}}},' for lo, hi in ranges)
    lines += ['}', '', 'var idLowerPairs = [...]idUnicodeLower{']
    lines.extend(f'\t{{0x{upper:04x}, 0x{lower:04x}}},' for upper, lower in pairs)
    lines += ['}', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--word-data', type=Path, required=True)
    parser.add_argument('--case-data', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = generate(args.word_data, args.case_data)
    if args.check:
        if args.output.read_text() != generated:
            raise SystemExit('Generated NuGet ID profile is stale')
        print('PASS: generated NuGet ID profile matches pinned Unicode inputs')
    else:
        args.output.write_text(generated)


if __name__ == '__main__':
    main()
