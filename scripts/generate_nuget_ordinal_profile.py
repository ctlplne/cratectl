"""Generate dependency comparison casing from hash-pinned official Unicode data."""
import argparse
import hashlib
from pathlib import Path

HASH15 = '2fc713e6a31a87c4850a37fe2caffa4218180fadb5de86b43a143ddb4581fb86'
HASH16 = 'ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f'


def mappings(path, digest):
    raw = path.read_bytes()
    if len(raw) > 4 << 20 or hashlib.sha256(raw).hexdigest() != digest:
        raise SystemExit('Unicode input does not match the pinned version/hash')
    pairs = []
    for line in raw.decode().splitlines():
        row = line.split(';')
        if len(row) != 15:
            raise SystemExit('Malformed pinned Unicode record')
        if row[12]:
            pairs.append((int(row[0], 16), int(row[12], 16)))
    return pairs


def generate(case_data, supplementary_data):
    lines = ['// SPDX-License-Identifier: BUSL-1.1 AND Unicode-3.0',
             '// Code generated by scripts/generate_nuget_ordinal_profile.py; DO NOT EDIT.',
             '// Unicode data copyright 1991-2026 Unicode, Inc. See third_party/licenses/Unicode-3.0.txt.',
             '// Invariant/ICU data: https://www.unicode.org/Public/15.1.0/ucd/UnicodeData.txt',
             '// SHA256: ' + HASH15,
             '// Supplementary ordinal/runtime data: https://www.unicode.org/Public/16.0.0/ucd/UnicodeData.txt',
             '// SHA256: ' + HASH16, 'package nuget', '',
             'const DependencyCaseProfile = "ordinal-bmp-u15.1.0-supplementary-u16.0.0-v1"', '',
             'type dependencyUpperPair struct{ from, to rune }', '',
             'var dependencyInvariantUpper = [...]dependencyUpperPair{']
    lines += [f'\t{{0x{a:x}, 0x{b:x}}},' for a, b in mappings(case_data, HASH15)]
    lines += ['}', '', 'var dependencySupplementaryUpper = [...]dependencyUpperPair{']
    lines += [f'\t{{0x{a:x}, 0x{b:x}}},' for a, b in mappings(supplementary_data, HASH16) if a > 0xffff]
    return '\n'.join(lines + ['}', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--case-data', type=Path, required=True)
    parser.add_argument('--supplementary-data', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate(args.case_data, args.supplementary_data)
    if args.check:
        if args.output.read_text() != result:
            raise SystemExit('Generated dependency casing profile is stale')
        print('PASS: dependency casing matches pinned Unicode inputs')
    else:
        args.output.write_text(result)
